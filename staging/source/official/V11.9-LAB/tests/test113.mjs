// Includes cross-layer V10.6 -> V11.2 offline E2E; no network or user data.
import assert from 'node:assert/strict';
import {make844} from '../legacy_v106/backup844.mjs';
import {empty84} from '../legacy_v106/model84.mjs';
import {seedGym} from '../legacy_v106/gym84.mjs';
import {preflight113,verifySameArchive113,describePlan113} from '../migration113.mjs';
import {rehearsal113} from '../scripts/rehearsal113.mjs';
let n=0;const check=(condition,msg)=>{assert.ok(condition,msg);n++;};
const mustReject=async(fn,pattern)=>{await assert.rejects(fn,pattern);n++};
const pass='frase de seguridad de datos sintéticos 2026';
const storage=new Map([['asia2027-v1',JSON.stringify({body:{},diet:{},work:{},photos:{},settings:{}})]]);
const fakeStore={readPair:async()=>({preferences:{revision:1,payload:empty84()},gym:{revision:1,payload:seedGym()}})};
const fakeStorage={getItem:k=>storage.get(k)??null};
const envelope=await make844(fakeStorage,fakeStore,pass);
const raw=JSON.stringify(envelope);
const preview=await preflight113(envelope,pass);
check(preview.sourceFormat==='asia84-portable-v1','legacy format');
check(preview.envelopeFormat==='asia84-encrypted-v1','outer format');
check(preview.withinCurrentStagingRequestLimit,'fixture small');
check(preview.components.length===5,'five payload components');
check(preview.counters.measurements===0&&preview.counters.gymSessions===0,'no hidden fake data');
check(preview.remoteTransferAllowed===false&&preview.productionMutationAllowed===false,'no real migration enabled');
check(preview.archiveSha256.length===64&&preview.contentFingerprint.length===64,'SHA256 lengths');
check(verifySameArchive113(envelope,preview),'same envelope');
check(!verifySameArchive113({...envelope,cipher:envelope.cipher.slice(0,-4)+'AAAA'},preview),'modified envelope');
check(!verifySameArchive113({...envelope,unknown:true},preview),'unknown extra attribute');
check(describePlan113(preview).importRequired===false,'offline only plan');
check(describePlan113(preview).originalPreserved===true,'rollback plan');
check(!JSON.stringify(preview).includes(pass),'secret never in report');
check(!JSON.stringify(preview).includes('2026'),'does not echo private notes/dates');
check(JSON.stringify(envelope)===raw,'input unchanged');
await mustReject(()=>preflight113(envelope,'bad'),/INVALID_PASSPHRASE/);
await mustReject(()=>preflight113(envelope,'long but invalid passphrase'),/INTEGRITY_OR_PASSWORD_FAILED/);
await mustReject(()=>preflight113({...envelope,format:'wrong-format'},pass),/NOT_INTEGRAL_ENCRYPTED_BACKUP/);
await mustReject(()=>preflight113({...envelope,token:'exfiltration'},pass),/NOT_INTEGRAL_ENCRYPTED_BACKUP/);
await mustReject(()=>preflight113({format:'asia84-encrypted-v1',salt:'abc',iv:'abc',cipher:'abc'},pass),/BACKUP_SIZE_OUT_OF_RANGE|INTEGRITY_OR_PASSWORD_FAILED/);
await mustReject(()=>preflight113(null,pass),/NOT_INTEGRAL_ENCRYPTED_BACKUP/);
await mustReject(()=>preflight113([],pass),/NOT_INTEGRAL_ENCRYPTED_BACKUP/);
await mustReject(()=>preflight113({...envelope,cipher:envelope.cipher.slice(0,-6)+'AAAAAA'},pass),/INTEGRITY_OR_PASSWORD_FAILED/);
await mustReject(()=>preflight113({...envelope,iv:(envelope.iv[0]==='A'?'B':'A')+envelope.iv.slice(1)},pass),/INTEGRITY_OR_PASSWORD_FAILED/);
check(!verifySameArchive113(null,preview),'null mismatch');
check(!verifySameArchive113(envelope,null),'null report');
assert.throws(()=>describePlan113(null),/NEED_VERIFIED_PREFLIGHT/);n++;
check(Object.isFrozen(preview)&&Object.isFrozen(preview.counters),'immutable reports');
const e2e=await rehearsal113({verbose:false});
check(e2e.passed===34,'34 full E2E checks');
console.log(`V11.3: ${n} validated assertions + ${e2e.passed} offline E2E checks. No network, no personal data.`);
