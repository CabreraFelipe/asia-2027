import assert from 'node:assert/strict';
import {validateExtractedPlan} from '../src/document-plan-import.mjs';
import {validateDietPlanBook,reviewDietPlan,applyDietPlan,dietDay,recordDietMeal,dietAdherence} from '../src/document-diet-plan.mjs';
const date='2026-11-30',next='2026-12-01',id='dietplan-'+'a'.repeat(32);
const document={version:1,kind:'diet',name:'Mi dieta',notes:'Tomar agua',uncertainties:[],days:[{label:'Día tipo',weekday:null,sections:[{label:'Desayuno',alternatives:[{label:'Opción A',items:[{name:'Avena',quantity:'50 g',source:'50 g de avena'}]},{label:'Opción B',items:[{name:'Pan',quantity:'2 rebanadas',source:'2 rebanadas de pan'}]}]},{label:'Almuerzo',items:[{name:'Arroz',quantity:null,source:'Arroz'}]}]}]};
assert.deepEqual(validateExtractedPlan(document),document);
const config={id,start:date,end:'2026-12-06',dayMap:[null,0,0,null,null,null,null]};
const book=validateDietPlanBook(undefined),review=reviewDietPlan(book,document,config,date);
assert.throws(()=>applyDietPlan(book,review,date));
assert.throws(()=>applyDietPlan(book,review,next,{confirmed:true}));
const saved=applyDietPlan(book,review,date,{confirmed:true});
assert.deepEqual(book,{version:1,plans:[],logs:[]});
assert.throws(()=>applyDietPlan(saved,review,date,{confirmed:true}));
assert.throws(()=>reviewDietPlan(saved,document,{...config,id:'dietplan-'+'b'.repeat(32)},date));
assert.throws(()=>reviewDietPlan(book,{...document,uncertainties:['Porción ilegible']},config,date));
assert.throws(()=>reviewDietPlan(book,{...document,days:[{...document.days[0],weekday:1}]},config,date));
const d=dietDay(saved,date);assert.equal(d.meals[0].alternatives.length,2);assert.equal(d.meals[1].alternatives[0].items[0].quantity,null);assert.equal(d.meals[0].log,null);
assert.equal(dietDay(saved,'2026-12-02'),null);
const entry={planId:id,day:date,meal:0,choice:1,status:'followed'};
assert.throws(()=>recordDietMeal(saved,entry,date));assert.throws(()=>recordDietMeal(saved,{...entry,day:next},date,{confirmed:true}));
assert.throws(()=>recordDietMeal(saved,{...entry,choice:8},date,{confirmed:true}));
let tracked=recordDietMeal(saved,entry,date,{confirmed:true});
tracked=recordDietMeal(tracked,{...entry,meal:1,choice:null,status:'skipped'},date,{confirmed:true});
tracked=recordDietMeal(tracked,{...entry,day:next,status:'partial'},next,{confirmed:true});
assert.equal(dietDay(tracked,date).meals[0].log.choice,1);
assert.deepEqual(dietAdherence(tracked,date,next,next),{scheduled:4,followed:1,partial:1,skipped:1,unrecorded:1,recorded:3,completionRate:.75,followedRate:1/3});
tracked=recordDietMeal(tracked,{...entry,status:'partial'},next,{confirmed:true});
assert.equal(tracked.logs.length,3);assert.equal(dietAdherence(tracked,date,next,next).followed,0);
assert.equal(saved.logs.length,0);
assert.throws(()=>validateDietPlanBook({...tracked,logs:[...tracked.logs,tracked.logs[0]]}));
console.log('Imported diet: alternatives, explicit schedule, missing quantities, consent, adherence and no automatic intake PASS');
