import assert from 'node:assert/strict';
import {hkdfSync,createDecipheriv} from 'node:crypto';
import {createWebPushSender} from '../src/notification-webpush-provider.mjs';
const now=1700000000000,origin='https://push.example.test',endpoint=origin+'/test';
const ua=await crypto.subtle.generateKey({name:'ECDH',namedCurve:'P-256'},true,['deriveBits']);
const pub=Buffer.from(await crypto.subtle.exportKey('raw',ua.publicKey)),auth=crypto.getRandomValues(new Uint8Array(16));
const sub={endpoint,keys:{p256dh:pub.toString('base64url'),auth:Buffer.from(auth).toString('base64url')}};
const vapid=await crypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},false,['sign','verify']);
const payload={version:1,kind:'rest',due:now-1000},requests=[];
const opts={enabled:true,origins:[origin],privateKey:vapid.privateKey,publicKey:vapid.publicKey,subject:'mailto:admin@example.test',now:()=>now,fetcher:async(url,init)=>{requests.push({url,init});return new Response(null,{status:201})}};
await assert.rejects(()=>createWebPushSender({...opts,enabled:false}));
const other=await crypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},false,['sign','verify']);
await assert.rejects(()=>createWebPushSender({...opts,publicKey:other.publicKey}));
const send=await createWebPushSender(opts);
assert.deepEqual(await send(sub,payload),{accepted:true,status:'accepted'});
const {url,init}=requests[0];assert.equal(url,endpoint);assert.equal(init.redirect,'error');assert.equal(init.headers.TTL,'299');assert.equal(init.headers['Content-Encoding'],'aes128gcm');
const [token,key]=init.headers.Authorization.slice(8).split(', k='),[h,c,sig]=token.split('.');
assert.equal(key,Buffer.from(await crypto.subtle.exportKey('raw',vapid.publicKey)).toString('base64url'));
assert.deepEqual(JSON.parse(Buffer.from(h,'base64url')),{typ:'JWT',alg:'ES256'});
assert.deepEqual(JSON.parse(Buffer.from(c,'base64url')),{aud:origin,exp:now/1000+3600,sub:opts.subject});
assert.equal(await crypto.subtle.verify({name:'ECDSA',hash:'SHA-256'},vapid.publicKey,Buffer.from(sig,'base64url'),Buffer.from(h+'.'+c)),true);
// Independently decrypt using Node's crypto implementation (not the sender's HKDF/AES helpers).
const b=Buffer.from(init.body),salt=b.subarray(0,16),len=b[20],serverPub=b.subarray(21,21+len),cipher=b.subarray(21+len);
assert.equal(b.readUInt32BE(16),4096);assert.equal(len,65);
const peer=await crypto.subtle.importKey('raw',serverPub,{name:'ECDH',namedCurve:'P-256'},false,[]);
const secret=await crypto.subtle.deriveBits({name:'ECDH',public:peer},ua.privateKey,256);
const info=s=>Buffer.concat([Buffer.from(s),Buffer.from([0])]);
const ikm=hkdfSync('sha256',Buffer.from(secret),auth,Buffer.concat([info('WebPush: info'),pub,serverPub]),32);
const cek=hkdfSync('sha256',Buffer.from(ikm),salt,info('Content-Encoding: aes128gcm'),16),nonce=hkdfSync('sha256',Buffer.from(ikm),salt,info('Content-Encoding: nonce'),12);
const d=createDecipheriv('aes-128-gcm',Buffer.from(cek),Buffer.from(nonce));d.setAuthTag(cipher.subarray(-16));
const plain=Buffer.concat([d.update(cipher.subarray(0,-16)),d.final()]);assert.equal(plain.at(-1),2);assert.deepEqual(JSON.parse(plain.subarray(0,-1)),payload);
await assert.rejects(()=>send({...sub,endpoint:'https://evil.test/test'},payload));
await assert.rejects(()=>send(sub,{...payload,notes:'private'}));
assert.equal((await send(sub,{...payload,due:now-300000})).status,'expired');
assert.equal(requests.length,1);
const gone=await createWebPushSender({...opts,fetcher:async()=>new Response(null,{status:410})});assert.deepEqual(await gone(sub,payload),{accepted:false,status:'gone'});
console.log('Web Push provider: VAPID signature, independently decrypted payload, expiry and strict destinations PASS');
